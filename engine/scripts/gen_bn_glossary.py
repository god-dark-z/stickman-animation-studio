def build() -> dict:
    return {
        "version": 1,
        "language": "bn",
        "note": (
            "Bangla commonsense intents. Same `requires` vocabulary and canonical visual "
            "requirements as data/intent-glossary.json, so qa_commonsense.ts checks both languages "
            "with one engine. Phrases include the idiomatic Bangla that is easy to misread."
        ),
        "entries": ENTRIES,
    }


def main(argv: list[str]) -> int:
    if "--check" in argv:
        if not os.path.exists(OUT):
            print(f"missing {OUT}")
            return 1
        data = json.load(open(OUT, encoding="utf8"))
        n = len(data["entries"])
        cats = sorted({e["category"] for e in data["entries"]})
        print(f"{OUT}: {n} entries across {len(cats)} categories: {', '.join(cats)}")
        return 0 if n >= 100 else 1
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    data = build()
    json.dump(data, open(OUT, "w", encoding="utf8"), ensure_ascii=False, indent=1)
    print(f"wrote {OUT}: {len(data['entries'])} entries across {len(CATEGORIES)} categories")
    print("categories:", ", ".join(CATEGORIES))
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
